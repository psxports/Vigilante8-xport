/* Bind the reviewed thirteen-track disc TOC after mounting its CUE */
sint32 v8_native_bind_disc_toc(void)
{
    static const CdlLOC toc[14] =
    {
        { 0x57u, 0x23u, 0x00u, 0x00u }, /* Leadout */
        { 0x00u, 0x02u, 0x00u, 0x00u }, /* Track 01 */
        { 0x24u, 0x22u, 0x00u, 0x00u }, /* Track 02 */
        { 0x26u, 0x54u, 0x00u, 0x00u }, /* Track 03 */
        { 0x29u, 0x40u, 0x00u, 0x00u }, /* Track 04 */
        { 0x32u, 0x25u, 0x00u, 0x00u }, /* Track 05 */
        { 0x35u, 0x07u, 0x00u, 0x00u }, /* Track 06 */
        { 0x37u, 0x55u, 0x00u, 0x00u }, /* Track 07 */
        { 0x40u, 0x32u, 0x00u, 0x00u }, /* Track 08 */
        { 0x43u, 0x16u, 0x00u, 0x00u }, /* Track 09 */
        { 0x46u, 0x15u, 0x00u, 0x00u }, /* Track 10 */
        { 0x48u, 0x55u, 0x00u, 0x00u }, /* Track 11 */
        { 0x51u, 0x32u, 0x00u, 0x00u }, /* Track 12 */
        { 0x54u, 0x14u, 0x00u, 0x00u }, /* Track 13 */
    };
    return CdSetToc(toc, 13);
}
